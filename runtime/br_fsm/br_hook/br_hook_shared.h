#pragma once

#include <atomic>
#include <cstdint>

/*
br_hook_shared - раскладка разделяемой памяти, через которую рантайм разговаривает с внешним
python-скриптом (хуком).

Это единственный канал обмена: ни сокета, ни канала, ни сигналов. Дескриптор самой памяти
скрипт получает аргументом (это POSIX-объект разделяемой памяти, имя которого рантайм снял
сразу после открытия), а все данные и вся синхронизация лежат здесь.

Стороны:
    рантайм (br_hook) - кладет кадр и боксы детекции, читает ответ;
    hook_main.py      - обвязка: читает кадр и боксы, зовет пользовательский скрипт, пишет ответ.

Раскладку видят обе стороны, поэтому она проверяется static_assert: все поля по 4 байта и без
выравнивающих дырок, так что одна и та же структура разбирается и из C++, и из python-форматов
(<IIIIIIIII - шапка, <iiiif24s - бокс).

Обмен по шагам (буфер под кадр скрипта один):

    0. скрипт:   поднялся, разобрал память и буфер кадра, отметил в _script_pid свой pid
    1. рантайм: RGA положил кадр с камеры в буфер скрипта (BGR888, как ждет cv2)
    2. рантайм: пишет _det_count, _frame_fd и боксы
    3. рантайм: последним пишет _state = filled
    4. скрипт:   видит filled, читает кадр и боксы, рисует прямо в буфере
    5. скрипт:   последним пишет _state = answered
    6. рантайм:  видит answered, забирает кадр, пишет _state = free

Порядок важен: состояние пишется последним и с release, а читается с acquire - поэтому
противоположная сторона никогда не увидит полузаполненные поля. Все остальное (боксы, размеры,
дескриптор кадра) - обычные поля: они пишутся до состояния и читаются после него, а порядок
им обеспечивает сам обмен состоянием. Между шагами 3 и 5 рантайм кадр скрипту не отдает:
пока не увидит free, он просто отправляет в поток текущие кадры с камеры.

Номеров кадров здесь нет намеренно: различать кадры сторонам не нужно. Рантайм ведет обмен по
_state, а просроченный ответ (в синхронном режиме вышел бюджет) он и так знает по своим пометкам -
кадр в этот момент просто отпускается, как только скрипт ответит.

Шаг 0 нужен потому, что запуск скрипта - дело небыстрое: импорт numpy в обвязке и cv2 в самом
скрипте на этой плате занимает секунды, и без отметки о готовности рантайм решал бы, что скрипт
завис, и убивал его прямо посреди импорта. До готовности рантайм кадры скрипту не считает и ждет свой срок запуска.

Режимы (оба работают на этой же раскладке):
    sync  - рантайм ждет шаг 6 с бюджетом _timeout_ms. Не дождался - в поток идет кадр с камеры,
            а просроченный ответ выбрасывается (чтобы старый кадр не подменил текущий);
    async - рантайм не ждет: отдал кадр и пошел дальше. Как только скрипт ответит, его кадр
            уходит в поток на следующем кадре вместо текущего, а пока скрипт работает - в поток
            идут текущие кадры.

Если скрипт вообще перестал отвечать (завис или умер), рантайм перезапускает его: см.
br_hook::poll и ключ stuck_ms в hook.ini.
*/

/*
Максимальное количество боксов в одном сообщении. Больше разбор модели все равно не отдает
(лимит рамок задается в model.ini).
*/
constexpr uint32_t BR_HOOK_BOXES_MAX = 64;

/* Длина имени класса вместе с завершающим нулем */
constexpr uint32_t BR_HOOK_CLASS_NAME_LEN = 24;

/*
Состояние обмена. Пишется последним при каждой передаче.

free     - буфер свободен, рантайм может положить новый кадр;
filled   - рантайм положил кадр, скрипт с ним работает;
answered - скрипт закончил, рантайм забирает кадр.
*/
enum br_hook_state : uint32_t
{
    BR_HOOK_FREE = 0,
    BR_HOOK_FILLED = 1,
    BR_HOOK_ANSWERED = 2,
};

/*
Бокс детекции: координаты в пикселях кадра (как их отдал разбор модели) и уверенность.
Имя класса строкой, потому что в br_model::detection лежит уже имя, а не индекс: скрипту не
нужно читать файл меток, чтобы подписать рамку.
*/
struct br_hook_box
{
    int32_t _left;
    int32_t _top;
    int32_t _right;
    int32_t _bottom;
    float _prop;
    char _name[BR_HOOK_CLASS_NAME_LEN];
};

/*
Разделяемая память целиком. Ровно на один буфер под кадр скрипта: второму буферу взяться
неоткуда, а его отсутствие - это и есть "скрипт еще работает, кадр не отдаем".

Атомарные поля - те, которые стороны пишут по очереди и читают друг у друга. Раскладка
при этом та же, что у скрипта: атомик на 4 байта - это те же 4 байта, что видит python
(см. static_assert ниже).
*/
struct br_hook_shared
{
    uint32_t _width; // ширина кадра в буфере: скрипту нужна для numpy
    uint32_t _height; // высота кадра в буфере
    int32_t _frame_fd; // дескриптор блока с кадром: скрипт делает по нему mmap
    // Пид скрипта: он пишет его, когда поднялся и разобрал память с буфером. Рантайм по нему
    // понимает, что скрипт на связи, и только после этого начинает считать его ответы
    std::atomic<int32_t> _script_pid;
    std::atomic<uint32_t> _state; // br_hook_state: единственное, о чем стороны договариваются
    uint32_t _det_count; // сколько боксов заполнено (0 - детекций нет)
    br_hook_box _boxes[BR_HOOK_BOXES_MAX];
};

/* Шапка без боксов: ровно эти поля разбирает скрипт - шесть по 4 байта */
constexpr uint32_t BR_HOOK_HEADER_SIZE = 24;

static_assert(std::atomic<uint32_t>::is_always_lock_free && std::atomic<int32_t>::is_always_lock_free,
              "атомики в разделяемой памяти должны быть без блокировок");
static_assert(sizeof(std::atomic<uint32_t>) == sizeof(uint32_t) &&
              sizeof(std::atomic<int32_t>) == sizeof(int32_t),
              "атомарное поле должно занимать те же 4 байта, что и в раскладке скрипта");
static_assert(sizeof(br_hook_box) == 44, "раскладка бокса должна совпадать с hook_main.py");
static_assert(sizeof(br_hook_shared) == BR_HOOK_HEADER_SIZE + BR_HOOK_BOXES_MAX * sizeof(br_hook_box),
              "раскладка разделяемой памяти должна совпадать с hook_main.py");
