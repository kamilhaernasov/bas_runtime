#pragma once

/*
 * br_model_yolo — разбор выходов YOLOv5 (anchor-based голова).
 *
 * Задача: превратить сырые int8-тензоры модели в список рамок в координатах кадра.
 * Файл модели, размер ее входа и геометрия кадра приходят в настройках от br_fsm, сами
 * тензоры — от br_npu. Своего у реализации только то, что она вычитала из файлов модели:
 * названия классов и якоря голов.
 *
 * Что модель отдает на выход. Голова YOLOv5 рамки не считает: она делит вход на сетку
 * и для каждой ячейки выдает набор чисел на каждый якорь. У модели 640x640 голов три,
 * они разной крупности — мелкая ловит мелкие объекты, крупная большие:
 * ├── голова 1: сетка 80x80, ячейка = 8x8 пикселей входа  (stride 8)
 * ├── голова 2: сетка 40x40, ячейка = 16x16 пикселей      (stride 16)
 * └── голова 3: сетка 20x20, ячейка = 32x32 пикселей      (stride 32)
 * stride считается, а не берется из константы: размер входа / размер сетки.
 *
 * Каждый тензор головы лежит как int8 в раскладке NHWC: [1, H, W, C], где каналов
 * C = якорей на голову * размер бокса. Размер бокса — 5 + число классов: четыре
 * координаты, уверенность объекта и оценки классов. Для нашей модели: 3 якоря по
 * 85 значений, то есть C = 255, а тензоры выглядят так:
 * ├── [1, 80, 80, 255]
 * ├── [1, 40, 40, 255]
 * └── [1, 20, 20, 255]
 * Раскладка внутри одного бокса:
 * ├── [0..3]  — tx, ty, tw, th: смещение центра и размер рамки относительно якоря;
 * ├── [4]     — уверенность объекта (objectness);
 * └── [5..84] — оценки классов (у нас 80 классов COCO).
 * Отсюда hw_offset у ячейки: (h * W + w) * (якоря * 85) + якорь * 85.
 * Оговорка про оси: у голов сетка квадратная, поэтому какая из dims[1] и dims[2]
 * высота, а какая ширина, разницы не дает. Понадобится неквадратная сетка — порядок
 * осей придется уточнить по строке dump_tensor_attr, которую печатает br_npu.
 *
 * Якоря и классы читаются из файлов, потому что относятся к самой модели, а не к
 * алгоритму разбора:
 * ├── файл якорей: 18 чисел парами (ширина, высота) — 9 якорей, поровну на три головы.
 * │   Первая тройка (10, 13), (16, 30), (33, 23) — якоря головы 80x80: она ищет мелкое,
 * │   поэтому и якоря маленькие. Взяли другую модель — взяли другой файл;
 * └── файл меток: по названию класса в строке, порядок строк совпадает с порядком
 *     классов в выходе модели. Число строк задает число классов (у нас 80).
 *
 * Что проверяет init, прежде чем разбор заработает:
 * ├── выходы модели квантованы в int8: только с такими работает этот разбор;
 * ├── пороги box_thresh и nms_thresh заданы: без них разбор не имеет смысла;
 * ├── геометрия вписывания (scale) известна: по ней рамки возвращаются в кадр;
 * ├── max_detections задан: при нуле рамок в кадре не будет;
 * ├── у модели есть выходы: голов не может быть ноль;
 * ├── число классов модели (5 + классы) совпадает с числом строк в файле меток:
 * │   метки и выход описывают одну модель и должны сходиться;
 * ├── число якорей делится на число голов, а каналы выхода — на якорей на голову;
 * └── файлы меток и якорей открылись.
 * Дальше разбор идет по этим числам (_head_count, _anchor_per_branch, _prop_box_size,
 * _class_num), а не по константам: подмена модели с другим числом голов или классов
 * настройки разбора не требует. Исключение одно — BOX_AND_CONF_SIZE: пятерка «четыре
 * координаты и уверенность» принадлежит алгоритму YOLOv5, из данных модели ее не вывести.
 *
 * Порядок разбора одного прогона (process):
 * 1. Голова за головой читается process_head: ячейка, внутри ячейки якорь, внутри
 *    якоря 85 чисел по смещению hw_offset.
 *    а) сначала сравнивается уверенность объекта, причем в int8: порог заранее переведен
 *       в int8 (qnt_f32_to_affine), потому что сравнивать целые дешевле, чем float;
 *    б) если прошла — ищется самый вероятный класс, оценки деквантуются в float
 *       (deqnt_affine_to_f32) и score = уверенность объекта * вероятность класса;
 *    в) score сравнивается с тем же порогом, но уже во float;
 *    г) рамка собирается обратно из чисел модели — формулы и пример ниже;
 *    д) координаты пока в пикселях входа модели, а не кадра.
 * 2. Кандидаты со всех голов лежат в одном списке: дубликаты между головами тоже
 *    возможны, одну и ту же вещь могут найти и мелкая сетка, и крупная.
 * 3. suppress_overlaps — подавление дубликатов: список сортируется по убыванию score,
 *    и рамка остается только тогда, когда со всеми уже оставленными рамками своего класса
 *    она пересекается слабее nms_thresh (пересечение считает overlap, это IoU). Рамки
 *    разных классов между собой не сравниваются: человек и его рюкзак перекрываются
 *    законно.
 * 4. Остаток уходит наружу в координатах кадра: из пикселей входа вычитаются поля
 *    letterbox и результат делится на масштаб вписывания, значения подрезаются по кадру.
 *    Рамок не больше max_detections, порядок — по убыванию уверенности.
 *
 * Деквантование: в тензоре лежат int8, а алгоритму нужны float, перевод — f = (q - zp) * scale.
 * Пример для головы 80x80 (у каждой головы свои zp и scale, их печатает br_npu при init):
 * ├── zp = -128, scale = 1/255 ≈ 0.0039215;
 * ├── q = -128 -> (−128 + 128) * 0.0039215 = 0.0;
 * ├── q = 0    -> (0 + 128)    * 0.0039215 ≈ 0.502;
 * └── q = 127  -> (127 + 128)  * 0.0039215 ≈ 1.0.
 *
 * Как из чисел модели получается рамка. Голова отдает не координаты, а то, что нужно
 * подставить в формулы: смещение центра внутри ячейки, размер относительно якоря
 * и уверенности. Якорь переводит размер в пиксели входа, stride — ячейку в пиксели:
 * ├── box_x = ((tx * 2 - 0.5) + w) * stride — центр по X: доля ячейки плюс номер ячейки;
 * ├── box_y = ((ty * 2 - 0.5) + h) * stride — центр по Y;
 * ├── box_w = ((tw * 2) ^ 2) * anchor_w — размер по X: доля от якоря;
 * ├── box_h = ((th * 2) ^ 2) * anchor_h — размер по Y;
 * └── углы рамки = центр минус половина размера и центр плюс половина размера.
 * Пример (числа упрощены). Пусть голова 80x80, ячейка w=40, h=40, якорь (10, 13),
 * и после деквантования получилось tx = 0.0, ty = 0.5, tw = 0.5, th = 0.5,
 * уверенность объекта 0.9, лучший класс 0.8:
 * ├── score = 0.9 * 0.8 = 0.72 — при box_thresh = 0.25 рамка проходит;
 * ├── центр: X = ((0.0 * 2 - 0.5) + 40) * 8 = 316, Y = ((0.5 * 2 - 0.5) + 40) * 8 = 324;
 * ├── размер: W = (0.5 * 2)^2 * 10 = 10, H = (0.5 * 2)^2 * 13 = 13;
 * ├── рамка в пикселях входа: left = 311, top = 317.5, right = 321, bottom = 330.5;
 * └── если рядом нашлась такая же рамка с score 0.5, то после NMS останется только эта.
 * Дальше в кадр. Для кадра 1920x1080 и входа 640x640 br_rga даст scale ≈ 0.333, pad_x = 0
 * и pad_y = 140 (вписывание по меньшей стороне, поля сверху и снизу), поэтому та же рамка
 * станет 933, 532, 963, 571 — уже в координатах кадра.
 */

#include <string>
#include <vector>

#include "br_model.h"

class br_model_yolo : public br_model
{
public:
    bool init(const model_info& model_info) override;
    bool process(const tensor* outputs, const int output_count, detection_list& detections) override;
    const char* get_class_name(const int cls_id) const override;
private:
    // Рамка-кандидат в координатах входа модели: так ее выдает голова модели, до порога
    // уверенности и подавления дубликатов.
    // left, top — левый верхний угол.
    // right, bottom — правый нижний угол.
    // score — уверенность: вероятность объекта, умноженная на вероятность класса.
    // cls_id — номер класса из модели.
    // Координаты дробные: округляются только при переводе в координаты кадра.
    struct box
    {
        float left;
        float top;
        float right;
        float bottom;
        float score;
        int cls_id;
    };

    // Файл меток: по названию класса в строке, число строк задает число классов модели
    bool load_labels(const std::string& path);

    // Файл якорей: числа парами (ширина, высота), по паре на якорь.
    // Идут подряд по головам: первая тройка — якоря первой головы (мелкая сетка), потом
    // следующей, и так до последней. Порядок обязан совпадать с порядком выходов модели
    bool load_anchors(const std::string& path);

    // Разбор одной головы модели: раскладка NHWC, деквантование и декодирование боксов.
    // output — выходной тензор этой головы.
    // head — номер головы: по нему берутся якоря этой головы и шаг сетки.
    // boxes — куда складываются найденные кандидаты (список общий на все головы).
    void process_head(const tensor& output, const int head, std::vector<box>& boxes) const;

    // Подавление дубликатов: на один объект модель часто выдает несколько похожих рамок.
    // Сравниваются только рамки одного класса, лишние выбрасываются из списка
    void suppress_overlaps(std::vector<box>& boxes) const;

    // Коэффициент пересечения двух рамок (IoU) = площадь пересечения / площадь объединения
    static float overlap(const box& a, const box& b);

    // Названия классов из файла меток: порядок совпадает с номерами классов модели
    std::vector<std::string> _labels;

    // Якоря голов парами (ширина, высота), подряд по головам
    std::vector<float> _anchors;

    // Форма голов, выверенная по модели и файлам в init.
    // _head_count — сколько голов у модели (сколько выходных тензоров).
    // _anchor_per_branch — сколько якорей приходится на одну голову.
    // _prop_box_size — сколько значений тензора описывают один бокс (координаты, уверенность, классы).
    // _class_num — сколько классов у модели (число строк в файле меток).
    // _model_height — высота входа модели: по ней считается шаг сетки головы.
    int _head_count = 0;
    int _anchor_per_branch = 0;
    int _prop_box_size = 0;
    int _class_num = 0;
    int _model_height = 0;
};
